CREATE TABLE IF NOT EXISTS live_challenge_discounts (
  id INTEGER PRIMARY KEY CHECK(id=1),
  tote INTEGER NOT NULL CHECK(tote BETWEEN 1 AND 100),
  nag INTEGER NOT NULL CHECK(nag BETWEEN 1 AND 100),
  outdoor INTEGER NOT NULL CHECK(outdoor BETWEEN 1 AND 100),
  mestre INTEGER NOT NULL CHECK(mestre BETWEEN 1 AND 100)
);
